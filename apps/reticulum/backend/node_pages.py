"""Read/write the ``.mu`` files a hosted NomadNet node serves.

Backs the Reticulum page's **Pages** tab -- an in-dashboard editor for the
Micron pages under ``plugins.reticulum.node_pages_dir`` (default
``data/reticulum/pages/``), so an operator running ``node_enabled`` doesn't
have to SSH in to write ``index.mu``.

Deliberately narrow:
  * only ``*.mu`` files, at the top level of the pages dir or exactly one
    level of subfolder beneath it (a "collection" -- e.g. the reticulum-
    scraper plugin's own output, ``pages/hulp/index.mu``). Never deeper,
    never ``files/`` (reserved for binary attachments) -- matches exactly
    what ``nomad_node.py`` actually walks and serves (``glob``, not
    ``rglob``), so this editor never claims to reach further than the
    server does.
  * ``info.mu`` / ``nodes.mu`` are refused **at the top level only**:
    ``nomad_node.py`` generates those and ignores an operator file of the
    same name there -- a collection-level ``hulp/info.mu`` doesn't collide
    with anything and is perfectly servable at ``/page/hulp/info.mu``.
  * plain files, never executable -- NomadNet runs a page as a script if
    its exec bit is set; "dynamic pages" stay an SSH-only thing on purpose.

The one-level collection-slug rule here is the same one
``scraper.py``'s crawler writes under (it imports
:func:`validate_collection_slug` from here rather than keeping its own
copy) -- one validator, not two drifting in parallel.

FastAPI-free -- the route layer (``nomad_routes.py``) passes the resolved
``pages_dir`` in, and this module is what the tests exercise directly.
"""

from __future__ import annotations

import re
import time
from pathlib import Path

# Generated by nomad_node.py and served unconditionally -- an operator file
# of the same name is ignored there, so the editor refuses to create one.
# Top-level only -- see module docstring.
RESERVED_NAMES = frozenset({"info.mu", "nodes.mu"})

# Lowercase slug + ".mu". No path separators, no leading dot, no "..".
_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,62}\.mu$")

# A collection folder name: lowercase slug, no dots (keeps it visually
# distinct from a filename at a glance). Same shape scraper.py writes.
_COLLECTION_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,31}$")
RESERVED_COLLECTIONS = frozenset({"files"})  # nomad_node.py's attachment dir

# Micron is plain text; a real page is a few KB. Generous cap, still small
# enough that a runaway paste can't fill the disk.
MAX_PAGE_BYTES = 128 * 1024

# sample-pages/index.mu, shipped next to the plugin -- the "Load sample"
# button's source.
_SAMPLE_INDEX = Path(__file__).resolve().parent.parent / "sample-pages" / "index.mu"


class PageError(ValueError):
    """A bad page path or oversized content -- carries an HTTP-ready message."""


def validate_collection_slug(slug: str) -> str:
    """Return *slug* unchanged if it's an acceptable collection (subfolder)
    name, else raise :class:`PageError`. Shared with ``scraper.py``."""
    if not isinstance(slug, str) or not _COLLECTION_RE.match(slug) or ".." in slug:
        raise PageError(
            "Folder name must be lowercase letters/digits/- (max 32 chars).",
        )
    if slug in RESERVED_COLLECTIONS:
        raise PageError(f"{slug!r} is reserved.")
    return slug


def validate_name(path: str) -> str:
    """Return *path* unchanged if it's an acceptable page path -- either a
    bare top-level filename (``"about.mu"``) or exactly one collection
    level (``"hulp/about.mu"``) -- else raise :class:`PageError`."""
    if not isinstance(path, str) or ".." in path or path.startswith("/"):
        raise PageError(
            "Page path must be 'name.mu' or 'folder/name.mu'.",
        )
    parts = path.split("/")
    if len(parts) == 1:
        name = parts[0]
        if not _NAME_RE.match(name):
            raise PageError(
                "Page name must be lowercase letters/digits/._- ending in '.mu'.",
            )
        if name in RESERVED_NAMES:
            raise PageError(
                f"{name!r} is generated by Meshpoint and can't be edited -- "
                "link to ':/page/info.mu' from your own index.mu instead.",
            )
        return path
    if len(parts) == 2:
        collection, name = parts
        validate_collection_slug(collection)
        if not _NAME_RE.match(name):
            raise PageError(
                "Page name must be lowercase letters/digits/._- ending in '.mu'.",
            )
        return path
    raise PageError("Only one folder level is supported.")


def _resolved(pages_dir: str | Path, path: str) -> Path:
    base = Path(pages_dir).resolve()
    target = (base / validate_name(path)).resolve()
    # Defense in depth -- validate_name()'s regexes already block
    # separators within a segment and ".." outright.
    if target.parent != base and target.parent.parent != base:
        raise PageError("Page path escapes the pages directory.")
    return target


def list_pages(pages_dir: str | Path) -> list[dict]:
    """Every editable ``*.mu`` file in the pages dir -- top-level first
    (``index.mu`` first then alphabetical, ``index.mu`` always listed even
    when absent, same as always), then every collection subfolder's own
    pages (grouped by appearing consecutively, alphabetical collection
    then alphabetical filename -- no synthetic placeholder entry, that's a
    top-level-only convenience). Each entry carries ``path`` (what the
    read/write/delete functions below -- and the API -- take) and
    ``collection`` (``None`` for a top-level page, else the folder name)
    alongside the existing ``name``/``exists``/``bytes``/``modified``."""
    base = Path(pages_dir)
    on_disk = {}
    if base.is_dir():
        for p in base.glob("*.mu"):
            if p.name in RESERVED_NAMES or not _NAME_RE.match(p.name):
                continue
            st = p.stat()
            on_disk[p.name] = {
                "name": p.name, "path": p.name, "collection": None,
                "exists": True, "bytes": st.st_size, "modified": int(st.st_mtime),
            }
    if "index.mu" not in on_disk:
        on_disk["index.mu"] = {
            "name": "index.mu", "path": "index.mu", "collection": None,
            "exists": False, "bytes": 0, "modified": 0,
        }
    top_level = sorted(
        on_disk.values(),
        key=lambda e: (e["name"] != "index.mu", e["name"]),
    )

    collections = []
    if base.is_dir():
        for coll_dir in sorted(base.iterdir()):
            if not coll_dir.is_dir() or coll_dir.name in RESERVED_COLLECTIONS:
                continue
            if not _COLLECTION_RE.match(coll_dir.name):
                continue
            for p in sorted(coll_dir.glob("*.mu")):
                if not _NAME_RE.match(p.name):
                    continue
                st = p.stat()
                collections.append({
                    "name": p.name, "path": f"{coll_dir.name}/{p.name}",
                    "collection": coll_dir.name,
                    "exists": True, "bytes": st.st_size, "modified": int(st.st_mtime),
                })

    return top_level + collections


def read_page(pages_dir: str | Path, path: str) -> str:
    """The file's text, or ``""`` if it doesn't exist yet."""
    target = _resolved(pages_dir, path)
    if not target.is_file():
        return ""
    return target.read_text(encoding="utf-8", errors="replace")


def write_page(pages_dir: str | Path, path: str, content: str) -> dict:
    """Create/overwrite a page. Creates the pages dir (and, for a
    collection path, the collection subfolder) if missing. Returns the
    same shape as a :func:`list_pages` entry."""
    if not isinstance(content, str):
        raise PageError("Page content must be text.")
    encoded = content.encode("utf-8")
    if len(encoded) > MAX_PAGE_BYTES:
        raise PageError(
            f"Page is {len(encoded)} bytes; the limit is {MAX_PAGE_BYTES}.",
        )
    target = _resolved(pages_dir, path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(encoded)
    target.chmod(0o644)  # never executable -- see module docstring
    st = target.stat()
    base = Path(pages_dir).resolve()
    collection = target.parent.name if target.parent != base else None
    return {
        "name": target.name, "path": path, "collection": collection,
        "exists": True, "bytes": st.st_size, "modified": int(st.st_mtime),
    }


def delete_page(pages_dir: str | Path, path: str) -> None:
    target = _resolved(pages_dir, path)
    if target.is_file():
        target.unlink()


def sample_index() -> str:
    """The bundled ``sample-pages/index.mu`` -- the 'Load sample' button."""
    try:
        return _SAMPLE_INDEX.read_text(encoding="utf-8")
    except OSError:
        return (
            f"`c`F38f`!MESHPOINT`!`f`a\n\n"
            f"Welcome to my node.\n\n"
            f">Links\n"
            f"`[Live stats`:/page/info.mu]\n\n"
            f"# edited {time.strftime('%Y-%m-%d')}\n"
        )
